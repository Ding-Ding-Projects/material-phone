import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const siteRoot = dirname(fileURLToPath(import.meta.url));
const inventory = JSON.parse(readFileSync(join(siteRoot, "data", "feature-inventory.json"), "utf8"));
const appSource = readFileSync(join(siteRoot, "app.ts"), "utf8");
const requestedCommit = process.env.SITE_COMMIT || "";
const requestedBuildTime = process.env.SITE_BUILD_TIME || "";
const requestedDocsBase = process.env.SITE_DOCS_BASE || "";

const buildMetadata = {
  commit: /^[0-9a-f]{40}$/.test(requestedCommit) ? requestedCommit : null,
  generatedAt: requestedBuildTime && !Number.isNaN(Date.parse(requestedBuildTime)) ? requestedBuildTime : null,
  docsBase: /^(?:\.\.\/)?docs\/$/.test(requestedDocsBase) ? requestedDocsBase : "../docs/"
};

const inventoryOutput = `// Generated from data/feature-inventory.json by build-site.mjs. Do not edit directly.\nwindow.MATERIAL_PHONE_FEATURES = ${JSON.stringify(inventory.features, null, 2)};\n`;
const appOutput = `// Generated from app.ts by build-site.mjs. Do not edit directly.\n${appSource}`;
const metadataOutput = `// Generated by build-site.mjs. Do not edit directly.\nwindow.MATERIAL_PHONE_BUILD = ${JSON.stringify(buildMetadata, null, 2)};\n`;

writeFileSync(join(siteRoot, "inventory.js"), inventoryOutput, "utf8");
writeFileSync(join(siteRoot, "app.js"), appOutput, "utf8");
writeFileSync(join(siteRoot, "metadata.js"), metadataOutput, "utf8");
